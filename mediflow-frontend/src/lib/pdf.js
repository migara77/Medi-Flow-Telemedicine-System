import jsPDF from 'jspdf';

export function downloadPrescriptionPdf(prescription) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 40;

  // Header band
  doc.setFillColor(8, 145, 178); // brand-600
  doc.rect(0, 0, pageWidth, 70, 'F');
  doc.setFontSize(22);
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.text('MediFlow', 40, 45);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text('Prescription', pageWidth - 110, 45);

  y = 110;
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(10);

  const dateStr = new Date(prescription.created_at || Date.now()).toLocaleDateString();
  const docName = prescription.doctor?.name || 'Doctor';
  const docSpec = prescription.doctor?.specialization || '';
  const patName = prescription.patient?.name || prescription.patient_name || 'Patient';

  doc.setFont('helvetica', 'bold');
  doc.text('Doctor:', 40, y);
  doc.setFont('helvetica', 'normal');
  doc.text(`${docName}${docSpec ? `  (${docSpec})` : ''}`, 110, y);

  doc.setFont('helvetica', 'bold');
  doc.text('Patient:', 40, y + 18);
  doc.setFont('helvetica', 'normal');
  doc.text(patName, 110, y + 18);

  doc.setFont('helvetica', 'bold');
  doc.text('Date:', 40, y + 36);
  doc.setFont('helvetica', 'normal');
  doc.text(dateStr, 110, y + 36);

  // Rx symbol
  doc.setFont('helvetica', 'bolditalic');
  doc.setFontSize(26);
  doc.setTextColor(8, 145, 178);
  doc.text('Rx', pageWidth - 80, 130);
  doc.setTextColor(15, 23, 42);

  // Medications table
  y = 180;
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('Medications', 40, y);
  y += 10;
  doc.setDrawColor(226, 232, 240);
  doc.line(40, y, pageWidth - 40, y);
  y += 18;

  const meds = Array.isArray(prescription.medications) && prescription.medications.length > 0
    ? prescription.medications
    : [{ name: prescription.medication_name, dosage: prescription.dosage, frequency: prescription.frequency, duration: prescription.duration }];

  doc.setFontSize(10);
  meds.forEach((m, i) => {
    doc.setFont('helvetica', 'bold');
    doc.text(`${i + 1}. ${m.name || '-'}`, 40, y);
    doc.setFont('helvetica', 'normal');
    const detail = `Dosage: ${m.dosage || '-'}    Frequency: ${m.frequency || '-'}    Duration: ${m.duration || '-'}`;
    doc.text(detail, 60, y + 14);
    y += 32;
  });

  if (prescription.instructions) {
    y += 8;
    doc.setFont('helvetica', 'bold');
    doc.text('Instructions', 40, y);
    y += 14;
    doc.setFont('helvetica', 'normal');
    const wrapped = doc.splitTextToSize(prescription.instructions, pageWidth - 80);
    doc.text(wrapped, 40, y);
    y += wrapped.length * 14;
  }

  if (prescription.notes) {
    y += 8;
    doc.setFont('helvetica', 'bold');
    doc.text('Notes', 40, y);
    y += 14;
    doc.setFont('helvetica', 'normal');
    const wrapped = doc.splitTextToSize(prescription.notes, pageWidth - 80);
    doc.text(wrapped, 40, y);
    y += wrapped.length * 14;
  }

  // Footer
  doc.setDrawColor(226, 232, 240);
  doc.line(40, 780, pageWidth - 40, 780);
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by MediFlow • This is a digitally issued prescription.', 40, 795);
  doc.text(`Ref #${prescription.id}`, pageWidth - 100, 795);

  const filename = `prescription-${prescription.id}.pdf`;
  doc.save(filename);
}
